#!/usr/bin/env python3
"""Regenerate the embedded, high-DPI application icon from the selected PNG.

ImageMagick is needed only when regenerating this checked-in resource.
SPDX-License-Identifier: Apache-2.0
"""

import argparse
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SIZE = 256
SOURCE = ROOT / f"assets/icons/png/liltview-color-{SIZE}.png"
OUTPUT = ROOT / "app/resources/icon_rgba.hpp"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the generated resource without rewriting it")
    args = parser.parse_args()
    pixels = subprocess.check_output(["magick", str(SOURCE), "-depth", "8", "RGBA:-"])
    if len(pixels) != SIZE * SIZE * 4:
        raise ValueError("Unexpected icon dimensions or pixel format")
    lines = [
        "// Generated by scripts/generate_icon.py. SPDX-License-Identifier: Apache-2.0",
        f"// Source: assets/icons/png/liltview-color-{SIZE}.png; RGBA8, straight alpha.",
        "#ifndef LILTVIEW_ICON_RGBA_HPP",
        "#define LILTVIEW_ICON_RGBA_HPP",
        "#include <array>",
        "namespace liltview::resources {",
        f"inline constexpr int icon_size = {SIZE};",
        f"inline constexpr std::array<unsigned char, {len(pixels)}> icon_rgba{{",
    ]
    for offset in range(0, len(pixels), 24):
        lines.append("    " + ", ".join(f"0x{value:02x}" for value in pixels[offset:offset + 24]) + ",")
    lines += ["};", "}", "#endif", ""]
    generated = "\n".join(lines)
    if args.check:
        if OUTPUT.read_text() != generated:
            raise ValueError("Embedded icon differs from source; run scripts/generate_icon.py")
        print(f"Verified {SIZE}x{SIZE} embedded icon matches the selected PNG.")
    else:
        OUTPUT.write_text(generated)
        print(f"Generated {OUTPUT.relative_to(ROOT)}: {SIZE}x{SIZE}, {len(pixels)} pixel bytes.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"Icon generation failed: {error}", file=sys.stderr)
        sys.exit(1)
